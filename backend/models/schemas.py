# ── PM checklists ───────────────────────────────────────────────────────────

class ChecklistTemplateOut(BaseModel):
    uuid:       str
    project_id: Optional[int] = None
    name:       str = ""
    kind:       str = ""
    # The items as the desktop numbered them: [{item_id, s_no, equipment,
    # activity, text, added}]. They travel with the template so the phone can
    # show a checklist it has not seen since its last sync.
    items:      List[dict[str, Any]] = Field(default_factory=list)
    updated_at: str = ""


class ChecklistTemplatesSyncRequest(BaseModel):
    templates: List[ChecklistTemplateOut]


class ChecklistRunOut(BaseModel):
    uuid:          str
    project_id:    int
    template_uuid: str
    plant_block:   Optional[int] = None
    campaign:      str = ""
    run_date:      str = ""
    status:        str = "In Progress"
    results:       dict[str, Any] = Field(default_factory=dict)
    ptw_no:        str = ""
    serial:        str = ""
    notes:         str = ""
    filled_by:     str = ""
    updated_at:    str = ""
    deleted_at:    Optional[str] = None


class ChecklistRunsSyncRequest(BaseModel):
    runs: List[ChecklistRunOut]


class ChecklistAssignedResponse(BaseModel):
    templates: List[ChecklistTemplateOut]
    runs:      List[ChecklistRunOut]
    # Paged by run uuid: the phone asks again with ?after=<cursor> while
    # has_more is true. A site with three checklists on each of 70 blocks is
    # more than one page, and a truncated list used to be silent.
    cursor:    str  = ""
    has_more:  bool = False


class ChecklistResultsIn(BaseModel):
    """What a phone sends back. Only the items it carries are touched, so a
    half-filled checklist never blanks the rest."""
    results:    dict[str, Any] = Field(default_factory=dict)
    status:     Optional[str] = None
    ptw_no:     Optional[str] = None
    serial:     Optional[str] = None
    filled_by:  Optional[str] = None
    notes:      Optional[str] = None
    updated_at: Optional[str] = None


class ChecklistRunPullResponse(BaseModel):
    runs:        List[ChecklistRunOut]
    cursor:      str
    # the second half of the cursor — a whole publish shares one timestamp
    cursor_uuid: str = ""
    has_more:    bool


# ── Action list ─────────────────────────────────────────────────────────────

class ActionItemOut(BaseModel):
    uuid:          str
    project_id:    int
    seq:           Optional[int] = None
    topic:         str = ""
    description:   str = ""
    todo:          str = ""
    due_date:      str = ""
    assigned_to:   str = ""
    assigned_name: str = ""
    status:        str = "open"
    done_at:       str = ""
    done_note:     str = ""
    done_by:       str = ""
    updated_at:    str = ""
    deleted_at:    Optional[str] = None


class ActionItemsSyncRequest(BaseModel):
    items: List[ActionItemOut]


class ActionItemsAssignedResponse(BaseModel):
    items:    List[ActionItemOut]
    # Paged by uuid, like the checklists: the phone asks again with
    # ?after=<cursor> while has_more is true.
    cursor:   str  = ""
    has_more: bool = False


class ActionItemDoneIn(BaseModel):
    """What a phone sends back when it finishes an item. Only the completion
    travels: the topic, the due date and the assignment are the office's."""
    status:     Optional[str] = None          # done | in progress
    done_note:  Optional[str] = None
    done_by:    Optional[str] = None
    done_at:    Optional[str] = None
    updated_at: Optional[str] = None


class ActionItemPullResponse(BaseModel):
    items:       List[ActionItemOut]
    cursor:      str
    # the second half of the cursor — a whole publish shares one timestamp
    cursor_uuid: str = ""
    has_more:    bool


# ── Sync ──────────────────────────────────────────────────────────────────────

class SyncChange(BaseModel):
    entity:  str                     # "work_log" | "work_log_image"
    id:      str
    action:  str                     # "upsert" | "delete"
    version: int
    payload: dict[str, Any]


class SyncPushRequest(BaseModel):
    device_id:       str
    changes:         List[SyncChange]
    idempotency_key: Optional[str] = None   # UUID; enables safe retry without false conflicts


class SyncChangeResult(BaseModel):
    id:             str
    outcome:        str                  # "applied" | "conflict" | "skipped" | "error"
    server_version: Optional[int]  = None  # new version after apply
    server_row:     Optional[dict] = None  # full server row on conflict (for UI merge)
    message:        Optional[str]  = None


class SyncPushResponse(BaseModel):
    results: List[SyncChangeResult]


class SyncPullChange(BaseModel):
    entity:     str
    action:     str                  # "upsert" | "delete"
    id:         str
    data:       dict[str, Any]
    updated_at: str


class SyncPullResponse(BaseModel):
    changes:  List[SyncPullChange]
    cursor:   str                    # ISO datetime — pass as `since` on next call
    has_more: bool


