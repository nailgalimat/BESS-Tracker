"""
models/schemas.py
------------------
Pydantic request / response schemas.
"""

from __future__ import annotations

from typing import Optional, List, Any
from pydantic import BaseModel, Field


# ── Auth ──────────────────────────────────────────────────────────────────────

class LoginRequest(BaseModel):
    username:  str
    password:  str
    device_id: Optional[str] = None


class RefreshRequest(BaseModel):
    refresh_token: str
    device_id:     Optional[str] = None


class UserOut(BaseModel):
    id:         str
    username:   str
    email:      Optional[str]
    role:       str
    created_at: str

    model_config = {"from_attributes": True}


class AssignableUser(BaseModel):
    """Who the office may give a job to — the name and nothing else. The
    desktop caches these so its "Assigned to" picker works offline."""
    id:       str
    username: str
    role:     str = ""

    model_config = {"from_attributes": True}


class TokenResponse(BaseModel):
    access_token:  str
    refresh_token: str
    token_type:    str = "bearer"
    user:          UserOut


class AccessTokenResponse(BaseModel):
    access_token:  str
    refresh_token: str          # new rotated refresh token
    token_type:    str = "bearer"


# ── Work log entries ──────────────────────────────────────────────────────────

class WorkLogEntryCreate(BaseModel):
    id:               str                    # UUID generated by client
    project_id:       int
    container_id:     Optional[int]   = None
    equipment_serial: str             = ""
    site_location:    str             = ""
    category:         str             = "maintenance"
    description:      str
    log_date:         str                    # YYYY-MM-DD
    created_at:       str
    updated_at:       str
    version:          int             = 1
    origin_device:    Optional[str]   = None
    tags:             List[str]       = Field(default_factory=list)


class WorkLogEntryUpdate(BaseModel):
    category:         Optional[str]   = None
    description:      Optional[str]   = None
    equipment_serial: Optional[str]   = None
    site_location:    Optional[str]   = None
    log_date:         Optional[str]   = None
    tags:             Optional[List[str]] = None


class WorkLogImageOut(BaseModel):
    id:             str
    work_log_id:    str
    filename:       str
    size_bytes:     int
    width:          Optional[int]
    height:         Optional[int]
    taken_at:       Optional[str]
    uploaded_at:    str
    updated_at:     str
    download_url:   str              # injected by router

    model_config = {"from_attributes": True}


class WorkLogEntryOut(BaseModel):
    id:               str
    user_id:          str
    # Optional: phone entries carry no project, and a required int made
    # GET /worklogs/{id} answer 500 for every one of them.
    project_id:       Optional[int] = None
    container_id:     Optional[int]
    equipment_serial: str
    site_location:    str
    category:         str
    description:      str
    log_date:         str
    created_at:       str
    updated_at:       str
    deleted_at:       Optional[str]
    version:          int
    origin_device:    Optional[str]
    tags:             List[str]      = Field(default_factory=list)
    images:           List[WorkLogImageOut] = Field(default_factory=list)

    model_config = {"from_attributes": True}


# ── Projects ──────────────────────────────────────────────────────────────────

class ProjectOut(BaseModel):
    id:           int
    name:         str
    project_type: str = "BESS"
    num_blocks:   int = 0
    # Zones as the plant really numbers them: [[zone, first block, last
    # block], ...]. The phone's node picker shows a zone grid with the
    # plant block numbers on it; without the real map it would have to
    # guess where a zone starts, and a guessed "Z4/B8" is worse than none.
    # Empty for an older desktop.
    zones:        str = ""


class ProjectsSyncRequest(BaseModel):
    projects: List[ProjectOut]


